// Generate a fixed asset table from the production bundle, never a filesystem server.
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("./", import.meta.url)),
  dist = root + "dist/";
const assets = [];
async function add(name, route, mime, alreadyGzip = false) {
  const source = await readFile(root + name),
    destination = "embedded/" + assets.length + ".gz";
  await writeFile(
    dist + destination,
    alreadyGzip ? source : gzipSync(source, { level: 9, mtime: 0 }),
  );
  assets.push([route, destination, mime]);
}
await mkdir(dist + "embedded", { recursive: true });
async function walk(prefix = "") {
  for (const entry of await readdir(dist + prefix, { withFileTypes: true })) {
    if (entry.name === "embedded") continue;
    const name = prefix + entry.name;
    if (entry.isDirectory()) await walk(name + "/");
    else {
      const mime = name.endsWith(".js")
        ? "text/javascript; charset=utf-8"
        : name.endsWith(".css")
          ? "text/css; charset=utf-8"
          : name.endsWith(".html")
            ? "text/html; charset=utf-8"
            : null;
      if (!mime) throw new Error("Unexpected build asset: " + name);
      await add(
        "dist/" + name,
        name === "index.html" ? "/ui/" : "/ui/" + name,
        mime,
      );
    }
  }
}
await walk();
await add(
  "rrc-schema.json.gz",
  "/ui/rrc-schema.json",
  "application/json",
  true,
);
await add(
  "licenses/RRC_SCHEMA_LICENSE.txt",
  "/ui/licenses/rrc",
  "text/plain; charset=utf-8",
);
await add(
  "licenses/RRC_SCHEMA_NOTICE.txt",
  "/ui/licenses/notice",
  "text/plain; charset=utf-8",
);
// Keep dependency notices in the embedded distribution, including packages that
// contribute only build-time generated code. No network access is needed here.
const notices = [];
async function licenses(directory) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return;
    throw error;
  }
  for (const entry of entries.sort((a, b) =>
    a.name.localeCompare(b.name, "en"),
  )) {
    if (!entry.isDirectory() || entry.name.startsWith(".")) continue;
    const path = directory + "/" + entry.name;
    if (entry.name.startsWith("@")) {
      await licenses(path);
      continue;
    }
    const info = JSON.parse(await readFile(path + "/package.json", "utf8"));
    const documents = (await readdir(path))
      .filter((name) => /^(licen[sc]e|copying|notice)(\..*)?$/i.test(name))
      .sort();
    const texts = await Promise.all(
      documents.map((name) => readFile(path + "/" + name, "utf8")),
    );
    notices.push(
      `${info.name}@${info.version}\nLicense: ${typeof info.license === "string" ? info.license : "see package notices"}\n${texts.join("\n\n")}`,
    );
    await licenses(path + "/node_modules");
  }
}
await licenses(root + "node_modules");
await writeFile(
  dist + "THIRD_PARTY_NOTICES.txt",
  notices.join("\n\n" + "=".repeat(72) + "\n\n"),
);
await add(
  "dist/THIRD_PARTY_NOTICES.txt",
  "/ui/licenses/dependencies",
  "text/plain; charset=utf-8",
);
const table =
  "// Generated by npm run build; do not edit.\npub(super) const ASSETS: &[(&str, &[u8], &str)] = &[\n" +
  assets
    .map(
      ([route, path, mime]) =>
        `    (${JSON.stringify(route)}, include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../web/dist/${path}")), ${JSON.stringify(mime)}),`,
    )
    .join("\n") +
  "\n];\n";
await writeFile(dist + "embedded.rs", table);
await writeFile(
  dist + "asset-manifest.json",
  JSON.stringify(assets, null, 2) + "\n",
);
console.log(
  `Embedded ${assets.length} bundled assets (gzip); no CDN or runtime Node.js required.`,
);
